CREATE TABLE IF NOT EXISTS auto_personal (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  first_name TEXT NOT NULL CHECK(first_name ~'^[A-Za-zА-Яа-я]+$'),
  last_name TEXT NOT NULL CHECK(last_name ~'^[A-Za-zА-Яа-я]+$'),
  father_name TEXT NOT NULL CHECK(father_name ~'^[A-Za-zА-Яа-я]+$')
);

COMMENT ON TABLE auto_personal IS 'Сотрудники автопарка';

CREATE TABLE IF NOT EXISTS auto (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    num SMALLINT NOT NULL CHECK(num >= 0),
    color TEXT NOT NULL CHECK(color ~'^[A-Za-zА-Яа-я]+$'),
    mark TEXT NOT NULL CHECK(mark ~'^[A-Za-zА-Яа-я]+$'),
    personal_id BIGINT,

    CONSTRAINT fk_auto_auto_personal
        FOREIGN KEY (personal_id)
        REFERENCES auto_personal(id)
        ON DELETE CASCADE
);

COMMENT ON TABLE auto IS 'Автомобили автопарка';

CREATE TABLE IF NOT EXISTS routes (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name TEXT NOT NULL CHECK(name ~'^[A-Za-zА-Яа-я]+$')
);

COMMENT ON TABLE routes IS 'Маршруты';

CREATE TABLE IF NOT EXISTS journal (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  time_out TIMESTAMP NOT NULL,
  time_in TIMESTAMP NOT NULL,
  route_id BIGINT,
  auto_id BIGINT,

  CONSTRAINT fk_journal_routes
    FOREIGN KEY (route_id)
    REFERENCES routes(id)
    ON DELETE CASCADE,

  CONSTRAINT fk_journal_auto
    FOREIGN KEY (auto_id)
    REFERENCES auto(id)
    ON DELETE CASCADE
);

COMMENT ON TABLE journal IS 'Журнал оператора';

