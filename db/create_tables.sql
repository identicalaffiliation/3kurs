SELECT r.name
FROM routes r
WHERE EXISTS (
    SELECT 1
    FROM journal j
    WHERE j.route_id = r.id
      AND j.time_in IS NULL
);

SELECT j.time_out, r.name
FROM routes r
LEFT JOIN journal j ON j.route_id = r.id
ORDER BY r.name, j.time_out;

SELECT j.time_out, j.time_in, r.name AS route_name, a.num AS auto_num
FROM routes r
FULL OUTER JOIN journal j ON j.route_id = r.id
FULL OUTER JOIN auto a ON a.id = j.auto_id
ORDER BY r.name, a.num, j.time_out;

SELECT a.num, j.time_in - j.time_out AS travel_time
FROM journal j
JOIN routes r ON r.id = j.route_id
JOIN auto a ON a.id = j.auto_id
WHERE r.name = 'Маршрут №1'
  AND j.time_in IS NOT NULL
ORDER BY travel_time ASC
LIMIT 1;

