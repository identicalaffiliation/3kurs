    j.time_in,
    ROW_NUMBER() OVER (
        PARTITION BY p.id
        ORDER BY j.time_out
    ) AS ride_number,
    EXTRACT(EPOCH FROM (
        j.time_out - LAG(j.time_in) OVER (
