/*
 * l1_server.c — Уровень 1 (A): разбор скелета Server.c
 *
 * 1. ftok -> ключ (один ключ годится и для памяти, и для семафоров).
 * 2. shmget(IPC_CREAT) — создать сегмент размером sizeof(Message).
 * 3. shmat — присоединить сегмент к своему адресному пространству.
 * 4. semget(key, 2, IPC_CREAT) — создать группу из двух семафоров (= 0).
 * 5. proc_wait — ждать, пока клиент начнёт работу.
 * 6. mem_lock — ждать, пока клиент освободит память, и занять её.
 * 7. Вывести сообщение, освободить память, сообщить клиенту и отключиться.
 *
 * Исправления скелета:
 *  - имена массивов: в скелете proc_lock/proc_unlock, а в shmem.h они
 *    называются mem_lock/mem_unlock;
 *  - shmat при ошибке возвращает (void *)-1, а не число < 0;
 *  - в скелете сервер занимает память и выходит, НЕ освободив её
 *    (комментарий «освободим» есть, а вызова semop нет) — клиент тогда
 *    ждал бы вечно. Здесь добавлен mem_unlock;
 *  - добавлено уведомление клиента «сервер прочитал» (семафор 1 + 1),
 *    иначе клиент мог удалить семафоры раньше, чем сервер их использует.
 */
#include "shmem.h"

int main(void)
{
    Message *msgptr;
    key_t key;
    int shmid, semid;

    setvbuf(stdout, NULL, _IONBF, 0);

    /* Получим ключ */
    if ((key = ftok(KEY_PATH, 'A')) < 0) { perror("Невозможно получить ключ"); exit(1); }

    /* Создадим область разделяемой памяти */
    if ((shmid = shmget(key, sizeof(Message), PERM | IPC_CREAT)) < 0) {
        perror("Невозможно создать область"); exit(1);
    }

    /* Присоединим её */
    if ((msgptr = (Message *)shmat(shmid, NULL, 0)) == (void *)-1) {
        perror("Ошибка присоединения"); exit(1);
    }

    /* Создадим группу из двух семафоров */
    if ((semid = semget(key, 2, PERM | IPC_CREAT)) < 0) {
        perror("Невозможно создать семафор"); exit(1);
    }
    printf("Сервер: shmid = %d, semid = %d, адрес сегмента = %p\n", shmid, semid, (void *)msgptr);
    printf("Сервер: жду клиента...\n");

    /* Ждём, пока клиент начнёт работу и заблокирует разделяемую память */
    if (semop(semid, &proc_wait[0], 1) < 0) { perror("Невозможно выполнить операцию"); exit(1); }

    /* Ждём, пока клиент закончит запись и освободит память. Затем заблокируем её */
    if (semop(semid, &mem_lock[0], 2) < 0) { perror("Невозможно выполнить операцию"); exit(1); }

    /* Выведем сообщение на терминал */
    printf("Сервер: в разделяемой памяти: %s", msgptr->buff);

    /* Освободим разделяемую память и сообщим клиенту, что прочитали */
    if (semop(semid, &mem_unlock[0], 1) < 0) { perror("mem_unlock"); exit(1); }
    if (semop(semid, &proc_start[0], 1) < 0) { perror("proc_start"); exit(1); }

    /* Отключимся от области */
    if (shmdt(msgptr) < 0) { perror("Ошибка отключения"); exit(1); }

    /* Всю остальную работу по удалению объектов сделает клиент */
    exit(0);
}
